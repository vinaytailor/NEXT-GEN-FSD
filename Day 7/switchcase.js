let fruit = "apple";
switch (fruit) {
    case "apple":
        console.log("Apple : 100 Rs/kg");
        break;
    case "banana":
        console.log("Banana : 40 Rs/kg");
        break;
    case "orange":
        console.log("Orange : 50 Rs/kg");
        break;
    default:
        console.log("Fruit not available");
}